import { expect, it } from "vitest";
import { MockAdapter } from "./MockAdapter";
import { satang } from "../../domain/model";
import type { OtherMoneyCommand } from "../../domain/workspace";
const command = (): OtherMoneyCommand => ({ commandId: "other-command-1", categoryId: "OTHER-02", amount: satang(1200000), date: "2026-10-16", fiscalYear: 2570, payer: "ชมรมศิษย์เก่าสาธิต", description: "สนับสนุนอุปกรณ์การเรียน", note: "", bookId: "book-380", pageId: "page-380-5", expectedPageVersion: 1, printedNo: "" });
it("school and other-money aggregates reconcile without sharing their numerator", async () => {
  const adapter = new MockAdapter(0), before = await adapter.dashboard("executive");
  expect(before.grades.reduce((s, g) => s + g.paid, 0)).toBe(480000000);
  expect(before.grades.reduce((s, g) => s + g.adjusted, 0)).toBe(540000000);
  const student = (await adapter.read()).student;
  const value = command();
  await adapter.receiveOther(value, "finance_officer");
  await adapter.receiveOther(value, "finance_officer");
  const after = await adapter.dashboard("executive");
  expect(after.grades).toEqual(before.grades);
  expect(after.other.reduce((s, g) => s + g.amount, 0)).toBe(9000000);
  expect((await adapter.read()).student).toEqual(student);
  expect((await adapter.read()).books[1].pages[4].transaction?.amount).toBe(1200000);
  await expect(adapter.receiveOther({ ...value, payer: "เปลี่ยน" }, "finance_officer")).rejects.toMatchObject({ code: "IDEMPOTENCY" });
  await expect(adapter.dashboard("homeroom_teacher")).rejects.toMatchObject({ code: "FORBIDDEN" });
});
it("other-money races, invalid fields, unauthorized and offline writes leave no partial cash", async () => {
  const adapter = new MockAdapter(0);
  const before = await adapter.read();
  await expect(adapter.receiveOther({ ...command(), categoryId: "SPT-111" }, "superadmin")).rejects.toMatchObject({ code: "VALIDATION" });
  await expect(adapter.receiveOther(command(), "finance_teacher")).rejects.toMatchObject({ code: "FORBIDDEN" });
  await expect(adapter.receiveOther({ ...command(), allocations: [] } as OtherMoneyCommand, "superadmin")).rejects.toMatchObject({ code: "VALIDATION" });
  expect(await adapter.read()).toEqual(before);
  adapter.setScenario("offline");
  await expect(adapter.receiveOther(command(), "superadmin")).rejects.toMatchObject({ code: "OFFLINE" });
  adapter.setScenario("baseline");
  const result = await Promise.allSettled([adapter.receiveOther(command(), "superadmin"), adapter.receiveOther({ ...command(), commandId: "competitor" }, "superadmin")]);
  expect(result.filter(r => r.status === "fulfilled")).toHaveLength(1);
  expect((await adapter.dashboard("executive")).other[1].amount).toBe(2800000);
});
it("unknown other-money outcome resolves by original key with exactly one receipt", async () => {
  const adapter = new MockAdapter(0); adapter.setScenario("unknown-outcome");
  await expect(adapter.receiveOther(command(), "superadmin")).rejects.toMatchObject({ code: "OUTCOME_UNKNOWN" });
  const resolved = await adapter.outcome(command().commandId);
  expect(resolved?.amount).toBe(1200000);
  expect(await adapter.receiveOther(command(), "superadmin")).toEqual(resolved);
});
it("linking an existing pending transaction changes only reference and audit, never cash twice", async () => {
  const adapter = new MockAdapter(0), before = await adapter.dashboard("executive"), account = (await adapter.read()).student;
  const value = { commandId: "link-1", transactionId: "pending-other-001", expectedTransactionVersion: 1, bookId: "book-380", pageId: "page-380-5", expectedPageVersion: 1, printedNo: "" };
  const linked = await adapter.linkReference(value, "finance_teacher");
  expect(await adapter.linkReference(value, "finance_teacher")).toEqual(linked);
  expect(await adapter.pendingReferences("finance_teacher")).toEqual([]);
  expect(await adapter.dashboard("executive")).toEqual(before);
  expect((await adapter.read()).student).toEqual(account);
  await expect(adapter.linkReference({ ...value, commandId: "link-2" }, "finance_teacher")).rejects.toMatchObject({ code: "VERSION_CONFLICT" });
});
it("access changes enforce source immutability, reason, final-admin and version protection", async () => {
  const adapter = new MockAdapter(0), users = await adapter.staffAccess("superadmin");
  const admin = users.find(s => s.role === "superadmin")!, teacher = users.find(s => s.role === "homeroom_teacher")!;
  await expect(adapter.changeAccess({ ...admin, active: false }, 1, "ทดสอบ", "superadmin")).rejects.toMatchObject({ code: "FINAL_ADMIN" });
  await expect(adapter.changeAccess(teacher, 1, "ทดสอบ", "executive")).rejects.toMatchObject({ code: "FORBIDDEN" });
  await expect(adapter.changeAccess({ ...teacher, name: "แก้ชื่อต้นทาง" }, 1, "ทดสอบ", "superadmin")).rejects.toMatchObject({ code: "VALIDATION" });
  await adapter.changeAccess({ ...teacher, rooms: [] }, 1, "สิ้นสุดการมอบหมาย", "superadmin");
  expect((await adapter.homeroomAccess("homeroom_teacher")).rooms).toEqual([]);
  await expect(adapter.changeAccess(teacher, 1, "ทดสอบ", "superadmin")).rejects.toMatchObject({ code: "VERSION_CONFLICT" });
});
